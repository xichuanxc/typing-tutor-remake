"""Generate browser resources from the immutable reference and retained analysis."""
from pathlib import Path
import hashlib
import json
import struct

root = Path(__file__).resolve().parents[1]
manifest = json.loads((root/"analysis/toolchain.json").read_text())
binary = (root/"analysis/derived/TT.unpacked.exe").read_bytes()
assert hashlib.sha256(binary).hexdigest() == next(a["sha256"] for a in manifest["artifacts"] if a["path"].endswith("TT.unpacked.exe"))
base=0xfae0
def text(offset):
    start=base+offset
    return binary[start:binary.index(0,start)].decode("cp437")
sections=(root/"TT/TT.HLP").read_text(encoding="ascii").split("^")
# The placeholders are original resource substitutions, not literal lesson keys.
help_sections=[[p.replace("'*'", "'ASDF'").replace("'#'", "'JKL;'").replace("\r","").replace("\n"," ").strip()
                for p in section.split("@") if p.strip()] for section in sections if section.strip()]
# Intro uses earlier text independently confirmed against the archived DOS distribution.
intro_path=root/"analysis/help-comparison/intro-reconstructed.txt"
intro_bytes=intro_path.read_bytes()
intro_receipt=json.loads((root/"analysis/help-comparison/internet-verification.json").read_text())
assert hashlib.sha256(intro_bytes).hexdigest() == intro_receipt["intro_sha256"]
intro_text=intro_bytes.decode("ascii").replace("\r\n","\n")
help_sections[0]=[p.replace("'*'", "'ASDF'").replace("'#'", "'JKL;'").replace("\n"," ").strip()
                  for p in intro_text.split("@") if p.strip()]
assert len(help_sections[0]) == 17
spec=json.loads((root/"analysis/settings/specification.json").read_text())
menus=json.loads((root/"analysis/recovered/menus.json").read_text())["menus"][:6]
data={"menus":menus,"choices":spec["choices"],"prompts":spec["prompts"],"help":help_sections,
      "idle":[text(o) for o in [0x17a6,0x185e,0x18a6,0x1997]],
      "optionTitles":{key:text(o) for key,o in {"wpm":0x1193,"weekly":0x11a5,"drills":0x11ba,"sound":0x11d5,"name":0x11eb,"intro":0x11fc}.items()},
      "practice":{key:text(o) for key,o in {"title":0x1043,"focus":0x1b91,"instruction":0x1bab,"speed":0x1c31,"accuracy":0x1c40,"summary":0x1b14,"end":0x1ae3,"prompt":0x102e}.items()},
      "practiceChoices":[text(p) for p in struct.unpack_from("<3H",binary,base+0x1ac8)],
      "quit":{"title":text(0x11d),"prompt":text(0x123),
              "choices":[text(p) for p in struct.unpack_from("<3H",binary,base+0xaf)]},
      "evidence":{"menus_sha256":hashlib.sha256((root/"analysis/recovered/menus.json").read_bytes()).hexdigest(),
                  "help_sha256":hashlib.sha256((root/"TT/TT.HLP").read_bytes()).hexdigest(),
                  "intro_source":"analysis/help-comparison/intro-reconstructed.txt",
                  "intro_sha256":hashlib.sha256(intro_bytes).hexdigest(),
                  "intro_archive_url":intro_receipt["download_url"],
                  "binary_sha256":hashlib.sha256(binary).hexdigest()}}
(root/"dist/original-data.js").write_text("// Generated by scripts/build-faithful-resources.py. Do not hand-edit.\nexport default "+json.dumps(data,ensure_ascii=False,indent=2)+";\n")
print("Generated original menu tables, exact option choices, prompts, introduction and help.")

control=list(" ☺☻♥♦♣♠•◘○◙♂♀♪♫☼►◄↕‼¶§▬↨↑↓→←∟↔▲▼")
cp437=control+[bytes([i]).decode("cp437") for i in range(32,256)]
cp437[127]="⌂"
assert len(cp437)==256
(root/"dist/cp437.js").write_text("// IBM PC code-page glyph mapping; generated with original resources.\nexport const CP437="+json.dumps(cp437,ensure_ascii=False)+";\n")
