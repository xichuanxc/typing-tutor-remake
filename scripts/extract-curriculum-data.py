"""Reproducibly extract curriculum tables; static evidence, not a DOS runtime capture."""
from pathlib import Path
import hashlib
import json
import struct

ROOT = Path(__file__).resolve().parents[1]
binary = (ROOT / "analysis/derived/TT.unpacked.exe").read_bytes()
manifest = json.loads((ROOT / "analysis/toolchain.json").read_text())
expected = next(a["sha256"] for a in manifest["artifacts"] if a["path"].endswith("TT.unpacked.exe"))
assert hashlib.sha256(binary).hexdigest() == expected
ds = binary[0xfae0:]
def cstr(offset):
    return ds[offset:ds.index(0, offset)].decode("cp437")
def words(offset, count):
    return list(struct.unpack_from("<" + str(count) + "H", ds, offset))
history = (ROOT / "TT/TT.HIS").read_bytes()
slot = next(i for i in range(9) if history[i*1996] == 0)
record = history[slot*1996:(slot+1)*1996]
def field(address):
    return record[address - 0x9072]
bootstrap = {
    "introduced": field(0x90af), "alphabetic": field(0x90ae),
    "newKey": field(0x90b2), "shiftPending": field(0x90b9),
    "shiftLearned": field(0x90ba),
    "thresholds": [field(0x90b3), field(0x90b4)],
    "weights": list(record[0x49:0x49+75]),
}
index = words(0x214e, 46*23)
dictionary = {}
ends = []
for offset in sorted(set(index)):
    position = (0x2992 + offset)*8
    def read5():
        global position
        value = 0
        for _ in range(5):
            assert position < len(ds)*8
            value = value*2 + ((ds[position//8] >> (7-position%8)) & 1)
            position += 1
        return value
    count = read5()
    entries = []
    for _ in range(count):
        length = read5()
        entries.append([read5() for _ in range(length)])
    dictionary[str(offset)] = entries
    ends.append((position+7)//8)
# Each dictionary block is separately addressed; decoding cannot run into the next block.
for offset, end in zip(sorted(set(index)), ends):
    next_offsets = [n for n in index if n > offset]
    assert end <= 0x2992 + min(next_offsets) if next_offsets else end <= 0x79ef+32
key_index = {}
for code in range(32, 127):
    normalized = code-32 if 97 <= code <= 122 else code
    if normalized > 122:
        normalized -= 26
    raw = ds[0x79ef+normalized]
    key_index[chr(code)] = raw if raw < 128 else raw-256
selection_offsets = [0x20e0,0x20e4,0x20eb,0x20f0,0x20f2,0x20f9,0x20ff,0x2102,0x2105,0x2108,0x210b,0x2113,0x20fb,0x210e,0x2116,0x2121,0x212b,0x2134,0x213b,0x213f,0x2141,0x2149,0x7aee,
                     0x85fe,0x8600,0x8602,0x8606,0x860d,0x8617,0x861a,0x8627]
guide_offsets = [0x1567,0x1ef0,0x1f21,0x1f4c,0x1f7d,0x1fb2,0x1a50,0x1c92,0x1d5c,0x1e04,0x1fd7]
data = {
    "presentation":cstr(0x7a53), "alphabetic":cstr(0x7af1),
    "alphabetFrequency":cstr(0x7aee), "keyIndex":key_index,
    "charFlags":list(ds[0x8e7d:0x8e7d+128]),
    "accuracyGoal":ds[0x1c90], "minSamples":ds[0x1c91],
    "punctuation":cstr(0x1c83), "bootstrap":bootstrap,
    "grammarOffsets":words(0x8632,51), "grammar":list(ds[0x8698:0x8879]),
    "callbacks":words(0x2088,44), "boundaries":words(0x1ed2,3),
    "earlyRanges":list(ds[0x1ed8:0x1ed8+23]),
    "defaultDictionaryClass":words(0x8893,1)[0],
    "dictionaryClasses":words(0x8879,32),
    "dictionaryIndex":[index[i*23:(i+1)*23] for i in range(46)],
    "dictionary":dictionary, "counterpart":ds[0x85b4:0x85b4+64].decode("ascii"),
    "selectionStrings":{format(o,"x"):cstr(o) for o in selection_offsets},
    "keyboardPositions":[list(ds[0x88ba+2*i:0x88ba+2*i+2]) for i in range(64)],
    "guideStrings":{format(o,"x"):cstr(o) for o in guide_offsets},
    "fingers":[ds[0x1a9b+7*i:0x1a9b+7*i+7].split(bytes([0]))[0].decode("ascii") for i in range(4)],
    "handRight":cstr(0x1a95),
}
assert bootstrap["introduced"] == 3 and len(bootstrap["weights"]) == 75
assert len(data["grammar"]) == 481 and data["grammarOffsets"][-1] == 476
assert len(dictionary) == 1058 and sum(map(len,dictionary.values())) == 4019
assert data["alphabetFrequency"] == "asdfjkleitnrohcpumygwvbxqz"
out = ROOT / "dist/curriculum-data.js"
out.write_text("// Generated by scripts/extract-curriculum-data.py; retained static executable evidence.\nexport default " +
               json.dumps(data, ensure_ascii=False, separators=(",",":")) + ";\n")
evidence = {
    "scope":"Static table extraction; no DOS runtime parity claim or named student data import",
    "binary_sha256":expected, "history_sha256":hashlib.sha256(history).hexdigest(),
    "bootstrap_source":{"unnamed_record_slot":slot,"record_bytes":1996,
                        "note":"Observed unnamed saved template, not a complete onboarding algorithm"},
    "data_segment_file_base":"0xfae0",
    "tables":{"grammar":"DS8698..8878; offsets DS8632[51]",
              "dictionary":"DS214e[46][23] uint16 offsets relative DS2992; MSB-first 5-bit symbols",
              "callbacks":"DS2088[44] code offsets, not string pointers",
              "character_classification":"DS8e7d[128]; key normalization 0x1722b, 0x1e793",
              "weights":"TT.HIS unnamed profile +0x49[75]",
              "counterparts":"DS85b4[64]; remaining terminator/extra bytes deliberately omitted"},
    "validation":{"dictionary_blocks":len(dictionary),"dictionary_words":sum(map(len,dictionary.values())),
                  "highest_dictionary_end_ds":hex(max(ends)),
                  "all_blocks_within_next_block":True,"grammar_bytes":len(data["grammar"])},
    "evidence_functions":["0x164cc","0x16629","0x1665a","0x16802","0x1722b","0x1e793","0x1bdcb","0x15854","0x157cc","0x168e3","0x169a0","0x16b2b","0x16b80","0x16f1b","0x17023","0x1708a","0x1714d","0x171ce","0x173ad","0x1745c","0x174ab","0x1757b","0x175e2","0x1c32b","0x1c98e"],
    "output_sha256":hashlib.sha256(out.read_bytes()).hexdigest(),
    "extractor_sha256":hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
}
path = ROOT / "analysis/curriculum/resources.json"
path.parent.mkdir(parents=True, exist_ok=True)
path.write_text(json.dumps(evidence, indent=2)+"\n")
print(json.dumps(evidence["validation"], sort_keys=True))
