"""Extract original fingering/keypad UI resources from the verified unpacked executable."""
from pathlib import Path
import hashlib,json,struct
ROOT=Path(__file__).resolve().parents[1]
binary=(ROOT/"analysis/derived/TT.unpacked.exe").read_bytes()
manifest=json.loads((ROOT/"analysis/toolchain.json").read_text())
expected=next(a["sha256"] for a in manifest["artifacts"] if a["path"].endswith("TT.unpacked.exe"))
assert hashlib.sha256(binary).hexdigest()==expected
ds=binary[0xfae0:]
def text(o):return ds[o:ds.index(0,o)].decode("cp437")
def choices(o,n):return [text(p) for p in struct.unpack_from("<"+"H"*n,ds,o)]
history=(ROOT/"TT/TT.HIS").read_bytes()
slot=next(i for i in range(9) if history[i*1996]==0)
record=history[slot*1996:(slot+1)*1996]
offsets={"fingeringTitle":0x106a,"lessonTitle":0x1053,"testTitle":0x10d5,"homeTitle":0x8c89,"summaryTitle":0x8cb8,
"intro":0x165d,"instruction":0x8be3,"speedLabel":0x8c6b,"accuracyLabel":0x8c7a,"speed":0x8cce,"accuracy":0x8cdc,"above":0x8ceb,"best":0x8d01,"worst":0x8d15}
data={k:text(v) for k,v in offsets.items()}
data.update(keys=ds[0x7b14:0x7b14+12].decode("ascii"),
 positions=[list(ds[0x8bcb+i*2:0x8bcd+i*2]) for i in range(12)],
 fingeringParagraphs=[text(o) for o in [0x8a63,0x8b01,0x8b78]],
 lessonChoices=choices(0x8bb2,3),testChoices=choices(0x1542,3),
 bootstrap={"introduced":record[0x90b0-0x9072],"pending":record[0x90b1-0x9072]})
assert data["keys"]=="4567891230.+"
assert data["bootstrap"]=={"introduced":66,"pending":1}
out=ROOT/"dist/keypad-data.js"
out.write_text("// Generated by scripts/extract-keypad-data.py; static REA evidence.\nexport default "+json.dumps(data,ensure_ascii=False,separators=(",",":"))+";\n")
functions=["0x1291c","0x1cd9b","0x1282a","0x12cc6","0x1cf2e","0x1d14c","0x1d1b8","0x1d2c9","0x1d368","0x1d6a0","0x12565"]
receipt={"scope":"Static fingering and keypad UI resources; no native runtime capture","binary_sha256":expected,
"history_sha256":hashlib.sha256(history).hexdigest(),"bootstrap_source":{"unnamed_record_slot":slot,"record_bytes":1996},
"strings":{k:hex(v) for k,v in offsets.items()},"functions":[{"address":a,"evidence":(ROOT/("analysis/recovered/"+a+".asm")).read_text().splitlines()[0].lstrip("; ")} for a in functions],
"output_sha256":hashlib.sha256(out.read_bytes()).hexdigest(),"extractor_sha256":hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
path=ROOT/"analysis/keypad/resources.json";path.parent.mkdir(parents=True,exist_ok=True);path.write_text(json.dumps(receipt,indent=2)+"\n")
print("Extracted original fingering/keypad resources and source hashes.")
