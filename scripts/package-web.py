"""Package the browser app as a reproducible static-host ZIP; no DOS files required."""
from pathlib import Path
import hashlib
import json
import shutil
import zipfile

ROOT = Path(__file__).resolve().parents[1]
DIST = ROOT / "dist"
SITE = ROOT / ".runtime/site"
OUTPUT = ROOT / "artifacts"
version = json.loads((ROOT / "package.json").read_text())["version"]
domain = (DIST / "CNAME").read_text().strip()
assert domain == "tt.xcstudio.dev"
prefix = "// Generated by scripts/build-faithful-resources.py. Do not hand-edit.\nexport default "
resource = (DIST / "original-data.js").read_text()
assert resource.startswith(prefix)
data = json.loads(resource[len(prefix):].strip().removesuffix(";"))
intro = (ROOT / data["evidence"]["intro_source"]).read_bytes()
assert hashlib.sha256(intro).hexdigest() == data["evidence"]["intro_sha256"]
assert len(data["help"][0]) == 17
assert not any("TiANWEi" in part for part in data["help"][0])

# This directory is owned by this packager; do not remove arbitrary existing content.
if SITE.exists():
    if SITE.is_symlink() or not (SITE / "BUILD.json").is_file():
        raise SystemExit("Refusing to replace an unmarked staging directory: " + str(SITE))
    shutil.rmtree(SITE)
SITE.mkdir(parents=True)
for source in sorted(DIST.rglob("*")):
    if source.is_symlink():
        raise SystemExit("Symlinks cannot be deployed: " + str(source))
    if not source.is_file():
        continue
    relative = source.relative_to(DIST)
    if source.suffix.lower() not in {".html", ".js", ".css"} and str(relative) not in {"CNAME", ".nojekyll"}:
        raise SystemExit("Unexpected web-root file: " + str(relative))
    destination = SITE / relative
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination)
for name in ["LICENSE", "COPYING.md", "THIRD_PARTY.md"]:
    shutil.copyfile(ROOT / name, SITE / name)
shutil.copyfile(ROOT / "docs/deployment.md", SITE / "DEPLOYMENT.md")
(SITE / "BUILD.json").write_text(json.dumps({
    "name": "Typing Tutor IV Remake",
    "version": version,
    "intended_domain": domain,
    "domain_status": "Host and DNS configuration managed separately from this artifact",
    "runtime": "Static HTML/CSS/JavaScript; HTTPS; no backend",
    "implementation_license": "MIT; historical content scoped separately in COPYING.md",
    "verified_intro_sha256": data["evidence"]["intro_sha256"],
    "repository": "https://github.com/xichuanxc/typing-tutor-remake",
}, indent=2) + "\n")
files = sorted(p for p in SITE.rglob("*") if p.is_file())
assert (SITE / "index.html").is_file() and (SITE / "prototype/index.html").is_file()
OUTPUT.mkdir(exist_ok=True)
basename = "typing-tutor-remake-v" + version + "-web"
archive = OUTPUT / (basename + ".zip")
temporary = OUTPUT / (basename + ".zip.tmp")
entries = []
with zipfile.ZipFile(temporary, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as bundle:
    for path in files:
        relative = path.relative_to(SITE).as_posix()
        content = path.read_bytes()
        info = zipfile.ZipInfo(relative, date_time=(1980, 1, 1, 0, 0, 0))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.create_system = 3
        info.external_attr = 0o100644 << 16
        bundle.writestr(info, content, compresslevel=9)
        entries.append({"path": relative, "bytes": len(content), "sha256": hashlib.sha256(content).hexdigest()})
temporary.replace(archive)
digest = hashlib.sha256(archive.read_bytes()).hexdigest()
manifest = {"name": "Typing Tutor IV Remake", "version": version, "intended_domain": domain,
            "archive": archive.name, "bytes": archive.stat().st_size, "sha256": digest, "files": entries}
(OUTPUT / (basename + ".manifest.json")).write_text(json.dumps(manifest, indent=2) + "\n")
(OUTPUT / (basename + ".zip.sha256")).write_text(digest + "  " + archive.name + "\n")
with zipfile.ZipFile(archive) as bundle:
    assert bundle.testzip() is None
    assert sorted(bundle.namelist()) == sorted(entry["path"] for entry in entries)
print("Packaged:", archive.relative_to(ROOT))
print("Files:", len(entries), "ZIP bytes:", archive.stat().st_size)
print("SHA-256:", digest)
print("Staged site:", SITE.relative_to(ROOT))
