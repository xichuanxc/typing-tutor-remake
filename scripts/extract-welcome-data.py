"""Extract the original startup screen, title music and history-file identity without exporting profiles."""
from pathlib import Path
import hashlib,json,struct
ROOT=Path(__file__).resolve().parents[1]
binary=(ROOT/"analysis/derived/TT.unpacked.exe").read_bytes()
manifest=json.loads((ROOT/"analysis/toolchain.json").read_text())
expected=next(row["sha256"] for row in manifest["artifacts"] if row["path"].endswith("TT.unpacked.exe"))
assert hashlib.sha256(binary).hexdigest()==expected
ds=binary[0xfae0:]
def text(offset):return ds[offset:ds.index(0,offset)].decode("cp437")
def tones(offset,count=1):return [struct.unpack_from("<IHH",ds,offset+8*i) for i in range(count)]
phrase=(tones(0x7bc8,6)+tones(0x7bf8)*2+tones(0x7c00,6)+tones(0x7bf8)*2
        +tones(0x7c30,2)+tones(0x7c40,3)+tones(0x7c58)+tones(0x7c40,3))
music=phrase+tones(0x7c60,7)+phrase+tones(0x7c98,7)
assert len(music)==64
data={
 "prompt":text(0x16b),"historyFile":text(0xa1),"profileBytes":0x7cc,"enumeratedSlots":8,
 "keyboard":{"top":ds[0x168],"left":ds[0x169]},
 "lines":[{"expected":text(0xe70),"replay":text(0xe84),"row":5,"col":30,"delayCentis":6},
          {"expected":text(0xe9c),"replay":text(0xeb5),"row":8,"col":28,"delayCentis":5}],
 "copyright":[text(0xbcd),text(0x9bb)],"registered":text(0x89db),
 "logo":{"top":14,"left":33,"rows":list(ds[0x8940:0x8972]),"cols":list(ds[0x8972:0x89a4]),
         "chars":ds[0x89a4:0x89d6].decode("cp437"),"colors":list(ds[0x89d6:0x89db])},
 "music":music,"titleKeyTone":tones(0x7b90)[0]
}
assert data["historyFile"]=="TT.HIS" and len(data["logo"]["chars"])==50
out=ROOT/"dist/welcome-data.js"
out.write_text("// Generated by scripts/extract-welcome-data.py; retained static REA evidence.\nexport default "+json.dumps(data,ensure_ascii=False,indent=2)+";\n")
functions=["0x10860","0x1095c","0x10c43","0x10bbb","0x1c78e","0x1c98e","0x1ca33","0x17e47","0x1804e","0x17a75","0x17ce8","0x14cb5","0x14d14","0x10128","0x10f47","0x10e3f","0x10ddc"]
receipt={"scope":"Startup screen/music and profile-file identity; no saved student names/history exported",
 "binary_sha256":expected,"output_sha256":hashlib.sha256(out.read_bytes()).hexdigest(),
 "extractor_sha256":hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
 "functions":[{"address":address,"sha256":hashlib.sha256((ROOT/("analysis/recovered/"+address+".asm")).read_bytes()).hexdigest()} for address in functions],
 "music":{"effect":"0x17e47 case7","phrase":"0x1804e","tables":"DS7bc8..7ccf","notes":64,"duration_ticks":sum((duration*182+5000)//10000+(rest*182+5000)//10000 for _,duration,rest in music)},
 "logo":{"rows":"DS8940[50]","columns":"DS8972[50]","characters":"DS89a4[50]","colors":"DS89d6[5]"},
 "profile":{"file":data["historyFile"],"record_bytes":data["profileBytes"],"enumeration_scans":data["enumeratedSlots"]},
 "limits":["Static recovery; video not retrieved and no native DOS runtime observation","First-visit-only browser gating and gesture start are owner-requested/browser adapters","Sub-tick title key pulses are not synthesized"]}
directory=ROOT/"analysis/welcome";directory.mkdir(parents=True,exist_ok=True)
(directory/"resources.json").write_text(json.dumps(receipt,indent=2)+"\n")
print("Extracted original welcome layout/logo,64-note title music and TT.HIS profile identity.")
