"""Extract report display resources from the verified unpacked DOS executable."""
from pathlib import Path
import hashlib
import json
import struct

ROOT = Path(__file__).resolve().parents[1]
binary = (ROOT / "analysis/derived/TT.unpacked.exe").read_bytes()
manifest = json.loads((ROOT / "analysis/toolchain.json").read_text())
expected = next(a["sha256"] for a in manifest["artifacts"] if a["path"].endswith("TT.unpacked.exe"))
assert hashlib.sha256(binary).hexdigest() == expected
ds = binary[0xfae0:]
def cstr(address):
    return ds[address:ds.index(0,address)].decode("cp437")
offsets = [0x7e26,0x7e2c,0x7e3d,0x7e49,0x7e52,0x7e58,0x7e5c,0x7e60,
           0x7e64,0x7e68,0x7e6c,0x7e70,0x7e74,0x7e87,0x7e93,0x7eb3,
           0x7ebe,0x7ed7,0x7ef3,0x7f1e,0x7f23,0x7f35,0x7f7a,0x113f,
           0x114f,0x115b,0x1009,0x101e,0x10af,0x10bd,0x10a3,0x843,0x102e]
presentation = cstr(0x7a53)
assert len(presentation) == 64
labels = presentation.upper()+ds[0x7ad4+64:0x7ad4+75].decode("cp437")
assert len(labels) == 75 and labels[-11:] == "4567891230."
data = {"strings": {format(o,"x"):cstr(o) for o in offsets},
        "labels":labels, "groups":[cstr(o) for o in [0x7f1e,0x7f23,0x7f35]],
        "titles":[cstr(o) for o in [0x113f,0x114f,0x115b]],
        "legend":["THIS SESSION","HISTORY","BOTH"],
        "testTitles":{"practice":cstr(0x10af),"allKeys":cstr(0x10bd)},
        "testChoices":[cstr(o) for o in struct.unpack_from("<3H",ds,0x153c)],
        "testPrompt":cstr(0x102e),"testResultPrefix":cstr(0x10a3),"testExit":cstr(0x843)}
out = ROOT / "dist/report-data.js"
out.write_text("// Generated by scripts/extract-report-data.py; static DOS evidence.\nexport default "+
               json.dumps(data,ensure_ascii=False,separators=(",",":"))+";\n")
functions = ["0x12d82","0x12de2","0x12e3b","0x18c42","0x18857","0x18ad2",
             "0x18357","0x18383","0x18497","0x184d1","0x1853c","0x14802","0x13a6d",
             "0x1b1f3","0x1f6bf"]
evidence = {"scope":"Static report geometry and resources; no DOS runtime capture",
            "binary_sha256":expected,"data_segment_file_base":"0xfae0",
            "functions":[{"address":f,"evidence":(ROOT/("analysis/recovered/"+f+".c")).read_text().splitlines()[0]} for f in functions],
            "geometry":{"table":{"top":3,"left":1,"right":78,"dividers":[38,55],"heading":7,"first_data":8},
                        "graph":{"axis_column":3,"top":2,"baseline":22,"first_key":4,"key_count":75,"labels_row":23},
                        "test":{"top":2,"left":1,"right":78,"bottom":22,"target_rows":[4,7,10,13,16,19],"first_column":3}},
            "navigation":"Any key cycles Progress -> Speed -> Accuracy -> Progress; Escape returns Main Menu; no current/history toggle or page selector in these paths.",
            "limits":["Browser font rasterization differs from DOS.","Native graph legend placement is translated from 0x184d1; no native screenshot comparison.","Instructor/multi-student report mode10 excluded.","DOS test frame is reconstructed from 0x13a6d(0,6,72,...) and 0x14802."],
            "output_sha256":hashlib.sha256(out.read_bytes()).hexdigest(),
            "extractor_sha256":hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
target=ROOT/"analysis/reports/resources.json"
target.parent.mkdir(parents=True,exist_ok=True)
target.write_text(json.dumps(evidence,indent=2)+"\n")
print("Extracted 75 graph labels and "+str(len(offsets))+" report strings.")
