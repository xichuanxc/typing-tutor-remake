"""Extract original Disk Test picker/resources from the verified unpacked image."""
from pathlib import Path
import hashlib,json,struct
ROOT=Path(__file__).resolve().parents[1]
binary=(ROOT/"analysis/derived/TT.unpacked.exe").read_bytes()
manifest=json.loads((ROOT/"analysis/toolchain.json").read_text())
expected=next(a["sha256"] for a in manifest["artifacts"] if a["path"].endswith("TT.unpacked.exe"))
assert hashlib.sha256(binary).hexdigest()==expected
ds=binary[0xfae0:]
def text(o):return ds[o:ds.index(0,o)].decode("cp437")
offsets={"mask":0xffe,"title":0x10cb,"suffix":0x1328,"noFiles":0x12fb,"pickerPrompt":0x854c,
"pickerInstruction":0x8516,"resultPrefix":0x10a3,"testPrompt":0x102e,"exit":0x843}
data={k:text(v) for k,v in offsets.items()}
data.update(choices=[text(p) for p in struct.unpack_from("<HHH",ds,0x153c)],
maxFiles=8,pickerWidth=13,emptyGeometry={"top":10,"left":22,"bottom":13,"right":56})
assert data["mask"]=="*.tst"
assert data["choices"]==["Take another test","Practice Lesson","Return to Main Menu"]
out=ROOT/"dist/disk-data.js"
out.write_text("// Generated by scripts/extract-disk-data.py; retained static REA evidence.\nexport default "+json.dumps(data,ensure_ascii=False,separators=(",",":"))+";\n")
functions=["0x12b58","0x1b5b2","0x1b21d","0x1b714","0x1b194","0x1b12a","0x12565"]
receipt={"scope":"Static Disk picker/resources; browser file import and filename aliases are explicit adapters, not native runtime observations",
"binary_sha256":expected,"strings":{k:hex(v) for k,v in offsets.items()},
"functions":[{"address":a,"evidence":(ROOT/("analysis/recovered/"+a+".asm")).read_text().splitlines()[0].lstrip("; ")} for a in functions],
"native_selection":{"mask":"*.tst","max_readable_files":8,"order":"DOS FindFirst/FindNext enumeration; no sort","encrypted_filter":False,"history_choice":False,"empty_geometry":data["emptyGeometry"]},
"browser_adapter":{"extensions":[".tst",".txt"],"order":"caller-selected order, first eight matching files","aliases":"uppercase sanitized first-eight-character basename plus .TST; collisions append ~n","retention":"caller owns imported bytes; resource extractor includes no test text"},
"output_sha256":hashlib.sha256(out.read_bytes()).hexdigest(),"extractor_sha256":hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}
path=ROOT/"analysis/disk/resources.json";path.parent.mkdir(parents=True,exist_ok=True);path.write_text(json.dumps(receipt,indent=2)+"\n")
print("Extracted original Disk Test resources and source hashes.")
